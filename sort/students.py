import json

# Створення словника з даними (українською)
students = {
    "Терновий": ["Дмитро", "Сергійович", 2005],
    "Шевченко": ["Тарас", "Григорович", 1814],
    "Коваленко": ["Олена", "Іванівна", 1998],
    "Мельник": ["Андрій", "Петрович", 2002],
    "Бондаренко": ["Марія", "Василівна", 1995],
    "Кравченко": ["Олексій", "Миколайович", 2000],
    "Лисенко": ["Ірина", "Сергіївна", 1997],
    "Петренко": ["Віталій", "Олександрович", 2004],
    "Сидоренко": ["Анна", "Володимирівна", 2001],
    "Гриценко": ["Максим", "Ігорович", 1999],
    "Іваненко": ["Софія", "Андріївна", 2003],
    "Дмитренко": ["Артем", "Володимирович", 1996]
}

# 1. Запис словника в JSON файл з правильним кодуванням
with open('students.json', 'w', encoding='utf-8') as f:
    json.dump(students, f, ensure_ascii=False, indent=4)

print("Файл 'students.json' успішно створено!")
print("(українські літери збережені коректно)\n")

# 2. Читання з JSON файлу
with open('students.json', 'r', encoding='utf-8') as f:
    data = json.load(f)

print("📋 Дані, прочитані з JSON-файлу:\n")
print("Прізвище".ljust(15), "Ім’я".ljust(12), "По батькові".ljust(15), "Рік народження")
print("-" * 65)

for surname, info in data.items():
    name, patronymic, year = info
    print(f"{surname.ljust(15)} {name.ljust(12)} {patronymic.ljust(15)} {year}")

print("\n" + "="*65)
print(f"Всього записів: {len(data)}")